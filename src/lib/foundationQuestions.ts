export type FoundationReviewStatus = "new" | "learning" | "practiced";
export interface FoundationQuestion {
  id: string; question: string; category: FoundationCategory; difficulty: "easy" | "medium" | "hard";
  applicableRoles: string[]; whyAsked: string; knowledgePoints: string[]; answerFramework: string[];
  commonFollowUps: string[]; reviewStatus: FoundationReviewStatus; learningNote: string;
}
type Row = [question: string, knowledge: string, framework: string, followUp: string];
const allRoles = ["AI 售前工程师", "AI 解决方案工程师", "AI 产品经理", "AI 产品运营", "AI 应用岗位"];
const productRoles = ["AI 产品经理", "AI 产品运营", "AI 应用岗位"];
const solutionRoles = ["AI 售前工程师", "AI 解决方案工程师", "AI 应用岗位"];
function group(code: string, category: FoundationCategory, rows: Row[], roles: string[], whyAsked: string): FoundationQuestion[] {
  return rows.map(([question, knowledge, framework, followUp], index) => ({
    id: `foundation-${code}-${String(index + 1).padStart(2, "0")}`, question, category,
    difficulty: index < 5 ? "easy" : index < 11 ? "medium" : "hard", applicableRoles: roles,
    whyAsked, knowledgePoints: knowledge.split("；"), answerFramework: framework.split("；"), commonFollowUps: [followUp],
    reviewStatus: "new", learningNote: knowledge,
  }));
}

