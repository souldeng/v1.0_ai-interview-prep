test("收集资料无需名称分类；AI来源校验、复用和删除刷新不进入个人事实", () => {
  const material = createCollectedMaterial("匿名面经.txt", "我做过20个项目。面试官问：如何评估RAG？");
  const raw = [{ materialId: material.id, type: "interview_experience", jobTitle: "", duties: [], requirements: [], skills: [], knowledgePoints: [], questions: [{ text: "如何评估RAG？", origin: "original", evidenceQuote: "如何评估RAG？", technical: true }] }];
  const items = validateMaterialExtractions([material], raw);
  const analysis = createCollectionAnalysis([material], items, { commonRequirements: [], topics: [], priorities: [] });
  assert.equal(analysis.questions[0].sourceType, "third_party");
  assert.equal(analysis.questions[0].collectionOrigin?.materialId, material.id);
  assert.deepEqual(collectionPracticeContext(emptyUserProfile(), analysis.questions[0]).confirmedUserFacts, []);
  assert.throws(() => validateMaterialExtractions([material], [{ ...raw[0], questions: [{ ...raw[0].questions[0], text: "你上线了20个项目吗？", evidenceQuote: "不存在的原文" }] }]), /依据|原文/);
  const collection = { materials: [material], analyses: [{ ...analysis, hiddenQuestionIds: [analysis.questions[0].id] }] };
  const values = new Map<string,string>(); const storage = { getItem: (k: string) => values.get(k) ?? null, setItem: (k: string,v: string) => { values.set(k,v); }, removeItem: (k: string) => { values.delete(k); } };
  saveQuestionLibrary({ ...emptyQuestionLibrary(), collection }, storage);
  assert.equal(loadQuestionLibrary(storage).collection?.analyses[0].hiddenQuestionIds?.[0], analysis.questions[0].id);
  assert.equal(currentCollectionAnalysis(collection, [material])?.id, analysis.id);
  assert.notEqual(collectionVersion({ ...material, content: "修改文字" }), collectionVersion(material));
  assert.equal(currentCollectionAnalysis(collection, [{ ...material, content: "修改文字" }]), undefined);
});
test("收集箱备份导入重映射资料/分析/题目与训练来源，附件缺失如实标注", () => {
  const m = { ...createCollectedMaterial("JD", "要求理解RAG"), fileId: "file-original", originalSaved: true };
  const items = validateMaterialExtractions([m], [{ materialId: m.id, type: "job_description", jobTitle: "", duties: [], requirements: ["理解RAG"], skills: [], knowledgePoints: [], questions: [{ text: "RAG如何工作？", origin: "derived", evidenceQuote: "理解RAG", technical: true }] }]);
  const a = createCollectionAnalysis([m], items, { commonRequirements: [], topics: [], priorities: [] });
  a.hiddenQuestionIds = [a.questions[0].id];
  const values = new Map<string,string>(); const s = { getItem: (k: string) => values.get(k) ?? null, setItem: (k: string,v: string) => { values.set(k,v); }, removeItem: (k: string) => { values.delete(k); } };
  saveQuestionLibrary({ ...emptyQuestionLibrary(), collection: { materials: [m],analyses: [a],extractions: items } },s);
  const session = nextTurn(startSession(trustedPreparation(collectionPracticeContext(emptyUserProfile(),a.questions[0]), [a.questions[0]])), "我的原始回答", { action: "next" });
  s.setItem("ai-interview-prep-history-v1", JSON.stringify([session]));
  importBackup(exportBackup(s),s);
  const copy = loadQuestionLibrary(s).collection!;
  assert.equal(copy.materials.length, 2); assert.equal(copy.analyses.length, 2);
  const source = copy.materials.find(item => item.id !== m.id)!;
  assert.equal(source.originalSaved, false); assert.equal(source.fileId, undefined);
  const generated = copy.analyses.find(item => item.id !== a.id)!;
  assert.equal(generated.questions[0].collectionOrigin?.materialId, source.id);
  assert.notEqual(generated.questions[0].id, a.questions[0].id);
  assert.equal(generated.hiddenQuestionIds?.[0], generated.questions[0].id);
  const history = JSON.parse(s.getItem("ai-interview-prep-history-v1")!);
  assert.equal(history[1].questions[0].collectionOrigin.analysisId, generated.id);
  assert.equal(history[1].turns[0].answer, "我的原始回答");
});
