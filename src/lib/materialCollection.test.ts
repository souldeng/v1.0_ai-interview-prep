test("批次归档、移除、下一批及备份读回不删除来源、失败信息和旧题ID",()=>{
  const m=createCollectedMaterial("匿名JD","要求检索"),bad=createCollectedMaterial("匿名失败","待核对");
  const items=validateMaterialExtractions([m],[{materialId:m.id,type:"job_description",jobTitle:"",duties:[],requirements:["检索"],skills:[],knowledgePoints:[],questions:[{text:"检索如何工作？",origin:"derived",evidenceQuote:"检索",technical:true}]}]);
  const result={...createCollectionAnalysis([m],items,{commonRequirements:[],topics:[],priorities:[]}),sources:[m,bad].map(s=>({materialId:s.id,contentVersion:collectionVersion(s)})),failures:[{materialId:bad.id,stage:"extraction" as const,message:"匿名失败：请核对"}]};
  const initial={materials:[m,bad],analyses:[],activeMaterialIds:[m.id,bad.id]};
  assert.throws(()=>nextCollectionBatch(initial,result),/先保存/);
  const saved=saveCollectionAttempt(initial,result);
  const removed=removeFromCollectionBatch(saved,m.id);
  assert.equal(removed.materials.length,2);assert.equal(removed.analyses[0].questions[0].id,result.questions[0].id);
  const next=nextCollectionBatch(saved,result);assert.equal(activeCollectionMaterials(next).length,0);assert.equal(next.materials.length,2);
  const retry=saveCollectionAttempt(saved,{...result,id:"new-attempt",questions:result.questions.map(q=>({...q,id:"new-q",collectionOrigin:{...q.collectionOrigin!,analysisId:"new-attempt"}}))});
  assert.equal(retry.analyses.length,1);assert.equal(retry.analyses[0].questions[0].id,result.questions[0].id);
  const corrected={...bad,content:"补充检索文字"};
  const fixedItems=validateMaterialExtractions([corrected],[{materialId:bad.id,type:"knowledge",jobTitle:"",duties:[],requirements:[],skills:[],knowledgePoints:["检索"],questions:[]}]);
  const recovered=saveCollectionAttempt({...saved,materials:[m,corrected]},{...result,items:[...items,...fixedItems],sources:[m,corrected].map(s=>({materialId:s.id,contentVersion:collectionVersion(s)})),failures:[]});
  assert.equal(recovered.analyses.length,1,"只修改失败项后重试，仍属于原批次");
  assert.equal(recovered.analyses[0].id,result.id);
  const data=new Map<string,string>(),storage={getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>{data.set(k,v)},removeItem:(k:string)=>{data.delete(k)}};
  saveQuestionLibrary({...emptyQuestionLibrary(),collection:next},storage);
  importBackup(exportBackup(storage),storage);
  const copy=loadQuestionLibrary(storage).collection!;
  assert.deepEqual(copy.activeMaterialIds,[]);
  assert.equal(copy.analyses.length,2);
  const imported=copy.analyses[1];
  assert.notEqual(imported.sources![0].materialId,m.id);
  assert.equal(imported.failures![0].materialId,imported.sources![1].materialId);
});
test("补齐失败JD后综合汇总失败，仍保留上次摘要及其来源范围，不冒称覆盖新增资料",()=>{
  const a=createCollectedMaterial("甲JD","理解检索"),b=createCollectedMaterial("乙JD","理解检索");
  const raw=(m:typeof a)=>({materialId:m.id,type:"job_description",jobTitle:"",duties:[],requirements:["理解检索"],skills:[],knowledgePoints:[],questions:[]});
  const items=validateMaterialExtractions([a],[raw(a)]);
  const previous={...createCollectionAnalysis([a],items,{commonRequirements:[{text:"理解检索机制",evidence:[{materialId:a.id,quote:"理解检索"}]}],topics:[],priorities:[]}),sources:[a,b].map(m=>({materialId:m.id,contentVersion:collectionVersion(m)})),failures:[{materialId:b.id,stage:"extraction" as const,message:"乙待补充"}]};
  const generated={...createCollectionAnalysis([a,b],validateMaterialExtractions([a,b],[raw(a),raw(b)]),{commonRequirements:[],topics:[],priorities:[]}),sources:previous.sources,failures:[],summaryError:"模型服务调用失败（503）"};
  const saved=saveCollectionAttempt({materials:[a,b],analyses:[previous]},generated);
  assert.equal(saved.analyses[0].commonRequirements[0]?.text,"理解检索机制");
  assert.deepEqual(saved.analyses[0].summaryMaterialIds,[a.id]);
  const data=new Map<string,string>(),storage={getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>{data.set(k,v)},removeItem:(k:string)=>{data.delete(k)}};
  saveQuestionLibrary({...emptyQuestionLibrary(),collection:saved},storage);
  importBackup(exportBackup(storage),storage);
  const copy=loadQuestionLibrary(storage).collection!.analyses[1];
  assert.equal(copy.summaryMaterialIds?.[0],copy.items[0].materialId);
});
